function reviewedAdjustmentText(value: unknown): value is string {
    return typeof value === 'string' && value.length <= 500 && (adjustmentMessages.has(value)
        || /^Недостаточно свободного остатка за (?:0[1-9]|1[0-2])\.\d{4}: доступно -?[\d ,\.\u00a0\u202f]+ ₸, перенос [\d ,\.\u00a0\u202f]+ ₸\. Факт и резервы не изменяются\.$/u.test(value));
}
export function adjustmentServerErrorMessage(value: unknown, fallback: string): string {
    if (!value || typeof value !== 'object' || Array.isArray(value))
        return fallback;
    const message = (value as Record<string, unknown>).message;
    return reviewedAdjustmentText(message) ? message : fallback;
}
